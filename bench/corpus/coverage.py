#!/usr/bin/env python3
"""Run queries on a coverage-instrumented osm3s_query and record each query's edge features.

The binary must be built with clang -fsanitize-coverage=inline-8bit-counters and linked with
cov_rt.c (in this directory), which writes the hit edges and a hit-count bucket to $COV_OUT.
A feature is edge * 16 + bucket, so the same edge taken 1, 2, 3, 4-7, 8-15, ... times counts as
different behaviour (as in AFL). See README.md here.

Sources (--source, repeatable):
  fuzz:SEED:FEATURES:START:COUNT   queries generated by fuzz.py (FEATURES comma-separated or empty)
  dir:PATH                         every *.ql file in PATH

Output: one JSON line per query: id, source, query, status, digest (fuzz.py's normalised output
hash), cpu seconds and features (sorted ints)."""
import argparse
import glob
import json
import multiprocessing
import os
import resource
import struct
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import fuzz  # noqa: E402


def expand(sources, vocab):
    for src in sources:
        kind, _, rest = src.partition(':')
        if kind == 'fuzz':
            seed, features, start, count = rest.split(':')
            feats = frozenset(f for f in features.split(',') if f)
            for i in range(int(start), int(start) + int(count)):
                yield f'fuzz:{seed}:{features}:{i}', ('fuzz', vocab, int(seed), i, feats)
        elif kind == 'dir':
            for path in sorted(glob.glob(os.path.join(rest, '*.ql'))):
                yield 'file:' + os.path.relpath(path), ('file', path)
        else:
            raise SystemExit(f'unknown source {src}')


def query_text(spec):
    if spec[0] == 'fuzz':
        _, vocab, seed, i, feats = spec
        return fuzz.generate(vocab, seed, i, feats)
    return open(spec[1]).read()


def read_features(path):
    feats = []
    try:
        data = open(path, 'rb').read()
    except FileNotFoundError:
        return None
    for off in range(0, len(data) - 4, 5):
        edge, bucket = struct.unpack_from('<IB', data, off)
        feats.append(edge * 16 + bucket)
    return sorted(feats)


def child_cpu():
    u = resource.getrusage(resource.RUSAGE_CHILDREN)
    return u.ru_utime + u.ru_stime


def work(task):
    qid, spec, bindir, db, timeout, tmpdir = task
    query = query_text(spec)
    cov = os.path.join(tmpdir, f'{os.getpid()}.cov')
    if os.path.exists(cov):
        os.unlink(cov)
    os.environ['COV_OUT'] = cov
    before = child_cpu()
    status, digest, _out, _peak = fuzz.run_once(bindir, db, query, timeout)
    cpu = child_cpu() - before
    feats = read_features(cov) if status not in fuzz.UNCACHEABLE else None
    return {'id': qid, 'query': query, 'status': status, 'digest': digest,
            'cpu': round(cpu, 4), 'features': feats}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--bin', required=True, help='bin directory of the instrumented build')
    ap.add_argument('--db', required=True)
    ap.add_argument('--vocab', required=True)
    ap.add_argument('--source', action='append', required=True)
    ap.add_argument('--out', required=True, help='JSON lines output')
    ap.add_argument('--timeout', type=int, default=60)
    ap.add_argument('--jobs', type=int, default=os.cpu_count())
    args = ap.parse_args()

    vocab = json.load(open(args.vocab))
    tmpdir = tempfile.mkdtemp(prefix='corpus-cov-')
    tasks = [(qid, spec, args.bin, args.db, args.timeout, tmpdir) for qid, spec in expand(args.source, vocab)]
    done = 0
    with open(args.out, 'w') as out, multiprocessing.Pool(args.jobs) as pool:
        for rec in pool.imap_unordered(work, tasks, chunksize=4):
            out.write(json.dumps(rec, separators=(',', ':')) + '\n')
            done += 1
            if done % 200 == 0:
                print(f'{done}/{len(tasks)}', file=sys.stderr, flush=True)
    print(f'{done} queries written to {args.out}', file=sys.stderr)


if __name__ == '__main__':
    main()
